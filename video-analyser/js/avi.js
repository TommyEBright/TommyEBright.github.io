// Reads MJPEG AVI files (lab high-speed cameras, Quintic) directly, frame by frame.
// Each frame in an MJPEG AVI is a JPEG, so the browser can decode it without converting the video.

// Returns { width, height, fps, frames: [[offset, size]], buf } or null if it is not an MJPEG AVI.
export function parseAvi(buf) {
  const dv = new DataView(buf), n = buf.byteLength;
  const tag = (o) => String.fromCharCode(dv.getUint8(o), dv.getUint8(o + 1), dv.getUint8(o + 2), dv.getUint8(o + 3));
  if (n < 12 || tag(0) !== 'RIFF' || tag(8) !== 'AVI ') return null;
  let fps = null, width = 0, height = 0, mjpeg = false;
  const frames = [];
  const walk = (start, end) => {
    let o = start;
    while (o + 8 <= end) {
      const id = tag(o), size = dv.getUint32(o + 4, true), d = o + 8;
      if (id === 'RIFF' || id === 'LIST') walk(d + 4, Math.min(d + size, end));
      else if (id === 'avih') { width = dv.getUint32(d + 32, true); height = dv.getUint32(d + 36, true); if (!fps) fps = 1e6 / dv.getUint32(d, true); }
      else if (id === 'strh' && tag(d) === 'vids') {
        if (/MJPG|AVRN|LJPG|JPEG/i.test(tag(d + 4))) mjpeg = true;
        const scale = dv.getUint32(d + 20, true), rate = dv.getUint32(d + 24, true);
        if (scale && rate) fps = rate / scale;
      } else if (id === 'strf' && d + 20 <= end && /MJPG|JPEG/i.test(tag(d + 16))) mjpeg = true;
      else if (/^\d\d(dc|db)$/.test(id) && size > 0) frames.push([d, size]);
      o = d + size + (size & 1); // chunks are padded to an even length
    }
  };
  walk(0, n);
  if (!frames.length) return null;
  if (!mjpeg && dv.getUint16(frames[0][0]) !== 0xFFD8) return null; // not JPEG frames
  return { width, height, fps: Math.round(fps * 1000) / 1000, frames, buf };
}

// Decode frame i to an ImageBitmap.
export function decodeFrame(avi, i) {
  const [off, len] = avi.frames[Math.max(0, Math.min(avi.frames.length - 1, i))];
  return createImageBitmap(new Blob([addHuffman(new Uint8Array(avi.buf, off, len))], { type: 'image/jpeg' }));
}

// Some cameras leave the standard Huffman tables out of each frame, and browsers need them.
function addHuffman(j) {
  let o = 2;
  while (o + 4 < j.length && j[o] === 0xFF) {
    const m = j[o + 1];
    if (m === 0xC4) return j;
    if (m === 0xDA) break;
    o += 2 + ((j[o + 2] << 8) | j[o + 3]);
  }
  const out = new Uint8Array(j.length + DHT.length);
  out.set(j.subarray(0, o)); out.set(DHT, o); out.set(j.subarray(o), o + DHT.length);
  return out;
}
